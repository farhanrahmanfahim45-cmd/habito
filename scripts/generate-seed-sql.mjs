/**
 * Turns src/data/seed.json into supabase/seed.sql.
 * Run: node scripts/generate-seed-sql.mjs
 *
 * IDs are derived from the original string keys, so reruns produce the same
 * UUIDs and the file can be replayed without duplicating rows.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";

const seed = JSON.parse(readFileSync("src/data/seed.json", "utf8"));

/** Deterministic UUID v5-shaped value from any stable string. */
function uuid(key) {
  const h = createHash("sha1").update(`habito:${key}`).digest("hex");
  return [
    h.slice(0, 8),
    h.slice(8, 12),
    "5" + h.slice(13, 16),
    ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16) + h.slice(17, 20),
    h.slice(20, 32),
  ].join("-");
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "NULL" : String(v));
const json = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const arr = (v) =>
  v && v.length ? `ARRAY[${v.map((x) => q(x)).join(",")}]::text[]` : `'{}'::text[]`;

const VERIFICATION = { verified: "verified", "identity-submitted": "pending", unverified: "unverified" };
const SPACE_VERIFICATION = {
  verified: "verified",
  reviewed: "pending",
  "documents-submitted": "pending",
  unverified: "unverified",
};

const lines = [
  "-- ============================================================================",
  "-- HABITO — synthetic seed data.",
  "--",
  "-- Invented listings used to demonstrate and test the platform. No real",
  "-- property, owner, photograph or availability is represented here. Every row",
  "-- is flagged is_seed = true so it can be told apart from anything a real",
  "-- user creates, and removed in one statement.",
  "--",
  "-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.",
  "-- ============================================================================",
  "",
  "begin;",
  "",
  "-- Replaying is safe: seed rows are cleared first. User data is untouched.",
  "delete from spaces where is_seed;",
  "delete from properties where is_seed;",
  "delete from profiles where is_seed;",
  "",
];

/* ── Owners ──────────────────────────────────────────────────────────────── */

lines.push("insert into profiles (id, name, avatar_tone, role, verification, response_rate, response_time_hours, is_seed, created_at) values");
lines.push(
  seed.owners
    .map((o) =>
      `  (${uuidLit(o.id)}, ${q(o.name)}, ${q(o.avatarTone)}, 'owner', ` +
      `'${VERIFICATION[o.verification] ?? "unverified"}', ${n(o.responseRate)}, ` +
      `${n(o.responseTimeHours)}, true, ${q(o.memberSince)}::timestamptz)`,
    )
    .join(",\n") + ";",
);
lines.push("");

/* ── Properties ──────────────────────────────────────────────────────────── */

lines.push("insert into properties (id, owner_id, name, area, neighborhood, address, district, geography, latitude, longitude, nearby, cover_image, verification, is_seed, created_at) values");
lines.push(
  seed.properties
    .map((p) =>
      `  (${uuidLit(p.id)}, ${uuidLit(p.ownerId)}, ${q(p.name)}, ${q(p.area)}, ` +
      `${q(p.neighborhood)}, ${q(p.address)}, ${q(p.district)}, '${p.geography}', ` +
      `${n(p.latitude)}, ${n(p.longitude)}, ${json(p.nearby)}, ${q(p.coverImage)}, ` +
      `'unverified', true, ${q(p.createdAt)}::timestamptz)`,
    )
    .join(",\n") + ";",
);
lines.push("");

/* ── Spaces ──────────────────────────────────────────────────────────────── */

lines.push("insert into spaces (id, property_id, name, category, space_type, transaction, status, price, service_charge, utilities, security_deposit, advance_months, attributes, amenities, availability, available_from, availability_note, total_units, available_units, images, description, verification, views, is_seed, created_at, updated_at) values");
lines.push(
  seed.spaces
    .map((s) => {
      const a = s.availability;
      return (
        `  (${uuidLit(s.id)}, ${uuidLit(s.propertyId)}, ${q(s.name)}, '${s.category}', ` +
        `${q(s.spaceType)}, '${s.transaction}', 'published', ${n(s.cost.price)}, ` +
        `${n(s.cost.serviceCharge)}, ${n(s.cost.utilities)}, ${n(s.cost.securityDeposit)}, ` +
        `${n(s.cost.advanceMonths)}, ${json(s.attributes)}, ${arr(s.amenities)}, ` +
        `'${a.status}', ${q(a.availableFrom)}::date, ${q(a.note ?? null)}, ` +
        `${n(a.totalUnits)}, ${n(a.availableUnits)}, ${json(s.images)}, ${q(s.description)}, ` +
        `'${SPACE_VERIFICATION[s.verification.space] ?? "unverified"}', ${n(s.views)}, true, ` +
        `${q(s.lastUpdated)}::timestamptz, ${q(s.lastUpdated)}::timestamptz)`
      );
    })
    .join(",\n") + ";",
);

lines.push("");
lines.push("commit;");
lines.push("");
lines.push("-- ---------------------------------------------------------------------------");
lines.push("-- Optional: hand the showcase portfolio to your own owner account so you can");
lines.push("-- test managing a property that already has spaces in it. Replace the email.");
lines.push("--");
lines.push("--   update properties set owner_id = (select id from profiles where email = 'you@example.com')");
lines.push("--   where name in ('Rahman Building', 'Rahman Annex', 'Rahman Bari');");
lines.push("-- ---------------------------------------------------------------------------");

function uuidLit(key) {
  return `'${uuid(key)}'::uuid`;
}

mkdirSync("supabase", { recursive: true });
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");

console.log(
  `wrote supabase/seed.sql — ${seed.owners.length} owners, ${seed.properties.length} properties, ${seed.spaces.length} spaces`,
);
